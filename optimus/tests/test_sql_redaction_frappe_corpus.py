"""The SQL redactor against statements Frappe really renders, and one secret followed from
capture through the report to the AI payload.

``data/frappe_sql_corpus.json`` is generated by ``scripts/gen_sql_corpus.py`` on a bench: the
statements come out of Frappe's query builder (pypika, MariaDB and PostgreSQL builders) and
pymysql's ``mogrify``, not from hand-typed SQL. The tests read only the JSON, so they need no Frappe.
"""

import json
import types
from pathlib import Path

import pytest

from optimus import redaction
from optimus.tests.test_recorder_redaction_patch import (  # noqa: F401
	_FakeRecorderInstance,
	_Recorder,
	_stub_recorder,
)

CORPUS = json.loads((Path(__file__).parent / "data" / "frappe_sql_corpus.json").read_text())
SECRET = "Zq9xK2vLm7Wp"
IDS = [f"{row['dialect']}-{row['source']}" for row in CORPUS]
SECRET_ROWS = [row for row in CORPUS if row["secrets"]]
SECRET_IDS = [f"{row['dialect']}-{row['source']}" for row in SECRET_ROWS]

# Statements that name no secret value: ordinary Frappe reads and writes.
ORDINARY = [
	"SELECT `name`, `title` FROM `tabToDo` WHERE `status`='Open' AND `owner`='a@b.c' LIMIT 20",
	"UPDATE `tabToDo` SET `status`='Closed', `modified`='2026-01-01 10:00:00.000000' WHERE `name`='TD-1'",
	"INSERT INTO `tabNote` (`name`, `title`, `content`) VALUES ('N-1', 'Meeting', 'agenda: tokens left')",
	"SELECT COUNT(*) FROM `tabSales Invoice` WHERE `posting_date` BETWEEN '2026-01-01' AND '2026-01-31'",
	"SELECT `user`, `last_login` FROM `tabUser` WHERE `enabled`=1 ORDER BY `modified` DESC",
	"SELECT `name` FROM `tabUser` WHERE `reset_password_key` IS NULL",
]


@pytest.mark.parametrize("row", SECRET_ROWS, ids=SECRET_IDS)
def test_real_frappe_statement_carries_no_secret_after_redaction(row):
	out, masked_whole = redaction.redact_sql_outcome(row["sql"], dialect=row["dialect"])
	assert not masked_whole, out
	assert redaction.OMITTED_SQL not in out
	for secret in row["secrets"]:
		assert secret not in out, out
	assert redaction.redact_sql_outcome(out, dialect=row["dialect"])[0] == out, "not idempotent"


@pytest.mark.parametrize("row", CORPUS, ids=IDS)
def test_real_frappe_statement_is_never_omitted_or_masked_whole(row):
	_, masked_whole = redaction.redact_sql_outcome(row["sql"], dialect=row["dialect"])
	assert not masked_whole


def test_ordinary_statements_stay_byte_identical_and_are_not_counted():
	calls = [{"query": sql, "normalized_query": sql} for sql in ORDINARY]
	counts = redaction.redact_call_queries(calls, dialect="mariadb")
	assert [call["query"] for call in calls] == ORDINARY
	assert counts == {"statements": len(ORDINARY), "masked_whole": 0, "omitted": 0}


def test_the_corpus_is_read_without_one_omitted_or_whole_masked_statement():
	"""A drift to omitting or masking most SQL shows here before it reaches a report."""
	for dialect in ("mariadb", "postgres"):
		calls = [{"query": row["sql"]} for row in CORPUS if row["dialect"] == dialect]
		counts = redaction.redact_call_queries(calls, dialect=dialect)
		assert counts["statements"] == len(calls) > 10
		assert counts["omitted"] == counts["masked_whole"] == 0


def test_the_corpus_comes_from_frappe_and_pymysql():
	sources = {row["source"].split(":")[0] for row in CORPUS}
	assert sources == {"qb", "mogrify"}
	assert {row["dialect"] for row in CORPUS} == {"mariadb", "postgres"}


# --- one secret from capture to the AI payload -------------------------------------------------------


def _register(data):
	fake = _FakeRecorderInstance()
	_Recorder().register(fake, data)
	return fake.calls[0]


def _doc(top_queries):
	return types.SimpleNamespace(
		name="PS-e2e", session_uuid="e2e-uuid", title="t", user="a@example.com", status="Ready",
		started_at="2026-05-12T00:00:00", stopped_at="2026-05-12T00:00:05", notes=None,
		top_severity="Low", summary_html=None, total_duration_ms=100, total_query_time_ms=80,
		total_queries=5, total_requests=1, top_queries_json=json.dumps(top_queries),
		table_breakdown_json="[]", hot_frames_json=None, session_time_breakdown_json=None,
		total_python_ms=None, total_sql_ms=None, analyzer_warnings=None, v5_aggregate_json="{}",
		actions=[], findings=[], phase_2_runs=[],
	)  # fmt: skip


E2E_ROWS = [row for row in SECRET_ROWS if row["dialect"] == "mariadb"]


@pytest.mark.parametrize("row", E2E_ROWS, ids=[f"{r['source']}" for r in E2E_ROWS])
def test_one_secret_never_reaches_storage_report_export_or_the_ai_payload(row, monkeypatch):
	from optimus import ai_privacy, renderer
	from optimus.renderer import _internal

	monkeypatch.setattr("optimus.dbdialect.redaction_dialect", lambda: "mariadb")
	monkeypatch.setattr(_internal, "redaction_dialect", lambda: "mariadb")
	monkeypatch.setattr(_internal, "_settings_extras", lambda: ((), ()))
	monkeypatch.setattr(ai_privacy, "_sensitive_columns", lambda: ())

	# Frappe's recorder derives ``normalized_query`` from the query after the capture patch ran.
	query = _register({"query": row["sql"]})["query"]
	top = [
		{
			"query_duration_ms": 900,
			"normalized_query": query,
			"query": query,
			"callsite": "apps/my_app/views.py:42 in my_app.views.do",
			"action_idx": 0,
			"recording_uuid": "r-1",
		}
	]
	exported = json.dumps(top)  # what the session JSON export carries
	rendered = [renderer.render_raw(_doc(top), recordings=[]), renderer.render(_doc(top), recordings=[])]
	ai_payloads = [ai_privacy.query_text(query, send_raw=raw) for raw in (True, False)]
	for secret in row["secrets"]:
		for where, text in [("stored", query), ("export", exported), ("ai", "\n".join(ai_payloads))] + [
			("report", html) for html in rendered
		]:
			assert secret not in text, f"{secret!r} leaked into the {where}"
	assert "my_app/views.py" in rendered[0], "the leaderboard did not render, so the check proved nothing"
